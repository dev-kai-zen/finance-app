/**
 * Generates src/constants/lucide-icon-catalog.generated.ts from lucide-react-native types.
 * Run: node scripts/generate-lucide-icon-catalog.cjs
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DTS_PATH = path.join(
  ROOT,
  "node_modules/lucide-react-native/dist/types/lucide-react-native.d.ts",
);
const OUT_PATH = path.join(ROOT, "src/constants/lucide-icon-catalog.generated.ts");

function pascalToKebab(pascal) {
  return pascal
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .replace(/(\d+)/g, "-$1")
    .toLowerCase()
    .replace(/^-/, "");
}

function titleFromKebab(kebab) {
  return kebab
    .split("-")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function keywordTokens(kebab) {
  const parts = kebab.split("-").filter(Boolean);
  return [kebab, ...parts];
}

const dts = fs.readFileSync(DTS_PATH, "utf8");
const pascalNames = [
  ...dts.matchAll(/\* @component @name ([A-Za-z0-9]+)/g),
].map((m) => m[1]);

const seen = new Set();
const entries = [];

for (const pascal of pascalNames) {
  const name = pascalToKebab(pascal);
  if (seen.has(name)) continue;
  seen.add(name);
  entries.push({
    name,
    label: titleFromKebab(name),
    keywords: keywordTokens(name),
  });
}

entries.sort((a, b) => a.name.localeCompare(b.name));

const lines = entries.map((e) => {
  const kw = JSON.stringify(e.keywords);
  return `  { name: ${JSON.stringify(e.name)}, label: ${JSON.stringify(e.label)}, keywords: ${kw} },`;
});

const output = `/** Generated by scripts/generate-lucide-icon-catalog.cjs — do not edit manually. */
export interface GeneratedLucideIconEntry {
  name: string;
  label: string;
  keywords: readonly string[];
}

export const LUCIDE_ICON_CATALOG: readonly GeneratedLucideIconEntry[] = [
${lines.join("\n")}
] as const;

export const LUCIDE_ICON_CATALOG_VERSION = ${JSON.stringify(
  require(path.join(ROOT, "node_modules/lucide-react-native/package.json")).version,
)} as const;
`;

fs.writeFileSync(OUT_PATH, output, "utf8");
console.log(`Wrote ${entries.length} icons to ${path.relative(ROOT, OUT_PATH)}`);
